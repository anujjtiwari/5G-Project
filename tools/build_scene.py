"""
Build a ray-tracing scene of a real site from OpenStreetMap and write a matching config.

Examples
--------
# IIT Gandhinagar (Palaj) campus, 1.4 km x 1.4 km, downloaded from OpenStreetMap:
python tools/build_scene.py --name iitgn --lat 23.2114 --lon 72.6821 --size 1400

# Same, from a GeoJSON file exported at https://overpass-turbo.eu (for machines without internet):
python tools/build_scene.py --name iitgn --lat 23.2114 --lon 72.6821 --size 1400 --geojson iitgn_buildings.geojson

Then run the whole study on it:
DT_CONFIG=config/iitgn.yaml python run_all.py
"""
import argparse, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import yaml
from dt.scene_builder import fetch_osm, load_geojson, build_scene

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--name", required=True, help="short scenario name, e.g. iitgn")
ap.add_argument("--lat", type=float, required=True, help="centre latitude (deg)")
ap.add_argument("--lon", type=float, required=True, help="centre longitude (deg)")
ap.add_argument("--size", type=float, default=1200, help="side of the square scene in metres")
ap.add_argument("--geojson", help="use this building GeoJSON instead of downloading from OSM")
ap.add_argument("--sites", type=int, default=3, help="number of gNB sites to place automatically")
ap.add_argument("--default-height", type=float, default=12.0, help="height for buildings without OSM height tags")
ap.add_argument("--building-material", default="concrete")
ap.add_argument("--ground-material", default="medium_dry_ground")
a = ap.parse_args()

feats = load_geojson(a.geojson) if a.geojson else fetch_osm(a.lat, a.lon, a.size)
print(f"{len(feats)} building features read")
out = ROOT / "scenes" / a.name
meta = build_scene(out, a.lat, a.lon, a.size, feats, a.default_height, a.sites,
                   a.building_material, a.ground_material, a.name)
print(f"scene written to {out}: {meta['num_buildings']} buildings, median height {meta['median_height_m']:.1f} m, "
      f"{meta['height_tagged_pct']}% with OSM height tags, built area {meta['built_area_pct']}%")
for s in meta["suggested_sites"]:
    print(f"  site {s['name']}: xy={s['xy']} m, mast height {s['height_m']} m (on {s['host_building']})")

# ---- write a config for this scene, starting from the default one
cfg = yaml.safe_load((ROOT / "config" / "scenario.yaml").read_text())
half = round(a.size / 2 - 50)
cfg["scene"] = dict(name=a.name, xml=str(Path("scenes") / a.name / f"{a.name}.xml"),
                    area_xy=[-half, half], seed=cfg["scene"]["seed"], hotspot_xy=[0.0, 0.0],
                    origin_lat=a.lat, origin_lon=a.lon)
cfg["ran"]["sites"] = [dict(name=s["name"], xy=s["xy"], height_m=s["height_m"]) for s in meta["suggested_sites"]]
cfg["output_tag"] = a.name
# a larger area needs more candidate positions and rays
scale = (a.size / 650) ** 2
cfg["experiments"]["pool_size"] = int(min(1500, 700 * scale))
cfg["raytracing"]["twin"]["samples_per_src"] = int(min(3e6, 3e5 * scale))
cfg["raytracing"]["physical"]["samples_per_src"] = int(min(1e7, 1e6 * scale))
cfg_path = ROOT / "config" / f"{a.name}.yaml"
header = (f"# Auto-generated by tools/build_scene.py for '{a.name}' "
          f"({a.lat}, {a.lon}), {a.size:.0f} m x {a.size:.0f} m.\n"
          "# Edit site positions/heights here (local metres: x = east, y = north of the centre).\n")
cfg_path.write_text(header + yaml.safe_dump(cfg, sort_keys=False))
print(f"config written to {cfg_path}")
print(f"next: DT_CONFIG=config/{a.name}.yaml python run_all.py")
